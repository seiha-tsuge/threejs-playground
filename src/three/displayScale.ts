/**
 * 物理値を画面上で見やすい Three.js のシーン単位へ変換するためのスケール。
 * 天体データや軌道を追加するときは、表示値をこのモジュールに集約する。
 */

/**
 * 距離の表示スケール。
 * 単位: Three.js のシーン単位 / 論理上の距離単位
 * 水星の軌道も太陽の表示半径（0.5）の外側に収まるようにする。
 * 水星の内縁は 0.387 * 2 - 0.0383 = 0.7357 となる。
 */
export const DISPLAY_DISTANCE_SCALE = 2

/**
 * 天体半径の表示スケール。
 * 単位: Three.js のシーン単位 / 論理上の半径単位
 *
 * 軌道半径は AU、天体半径は地球半径を論理単位にしているため、同じ
 * スケールを使うと惑星の半径が軌道半径を上回る。惑星を軌道上に配置
 * できるよう、半径は距離より小さい表示倍率にする。
 */
export const DISPLAY_RADIUS_SCALE = 0.1

/**
 * 時間の表示スケール。公転速度などのアニメーションに適用する。
 * 単位: 表示上の経過秒 / 実時間の秒
 */
export const DISPLAY_TIME_SCALE = 1
